"""Thoron's release build configuration (ROADMAP P2.17).

The release `args.gn` is upstream Thorium's args file for the platform with Thoron's deliberate
choices applied. Every choice that touches privacy or network contact is listed in DECISIONS, with
its reason; `compose` writes that reason next to the value, and `check` refuses an args file that
differs from them or carries Google API keys. The full review is in `docs/build/RELEASE_ARGS.md`.
    py -3 -I tools/build/release_args.py compose --upstream <upstream>/other/AVX2/win_AVX2_args.gn
        --platform win --source "gz83 efc0fff other/AVX2/win_AVX2_args.gn" --out out/<dir>/args.gn
    py -3 -I tools/build/release_args.py check --args out/<dir>/args.gn --platform win
"""
import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

PLATFORMS = ("win", "linux")
TOOL = "tools/build/release_args.py"


class ArgsError(Exception):
    pass


@dataclass(frozen=True)
class Decision:
    name: str
    value: str          # GN literal
    platforms: tuple
    reason: str


_ALL = PLATFORMS
DECISIONS = (
    Decision("enable_rlz", "false", _ALL,
             "Google's RLZ promotion-tracking library stays out; Chromium leaves it off for non-Google builds"),
    Decision("enable_cdm_storage_id", "false", _ALL,
             "No per-device storage ID for DRM modules; without a private key it only read the machine ID"),
    Decision("bundle_widevine_cdm", "false", _ALL,
             "Google's proprietary Widevine module is never shipped; Chromium downloads it when a site needs it"),
    Decision("enable_widevine", "true", _ALL,
             "DRM video sites keep working; the module comes from Google's component updater only on demand"),
    Decision("use_official_google_api_keys", "false", _ALL,
             "No Google API keys: sync, Google sign-in and other keyed Google services stay off"),
    Decision("enable_reporting", "false", _ALL,
             "Web pages cannot make the browser send Reporting API or Network Error Logging reports"),
    Decision("enable_hangout_services_extension", "false", _ALL,
             "No hidden component extension that gives Google Meet pages extra system information"),
    Decision("disable_fieldtrial_testing_config", "true", _ALL,
             "No Google field-trial configuration compiled in; features keep their coded defaults"),
)
# Google API keys and OAuth client IDs must never be set to a value in a release build.
_KEY_ARGS = re.compile(r"^(google_api_key|google_default_client_id|google_default_client_secret)$")
_LINE = re.compile(r"^(?P<name>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*(?P<value>[^#]*?)\s*(?:#.*)?$")


def decisions(platform: str) -> list[Decision]:
    if platform not in PLATFORMS:
        raise ArgsError(f"unknown platform {platform!r} (expected one of {', '.join(PLATFORMS)})")
    return [d for d in DECISIONS if platform in d.platforms]


def parse(text: str) -> dict[str, str]:
    """name -> value of every assignment; raises on an argument assigned twice."""
    out: dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = _LINE.match(line)
        if not m:
            raise ArgsError(f"cannot read args line: {raw!r}")
        if m["name"] in out:
            raise ArgsError(f"{m['name']} is assigned twice")
        out[m["name"]] = m["value"]
    return out


def compose(upstream: str, platform: str, source: str) -> str:
    """Upstream's args with Thoron's decisions applied (in place, or appended); idempotent."""
    wanted = {d.name: d for d in decisions(platform)}
    parse(upstream)   # rejects duplicates and unreadable lines
    out = [f"# Generated by {TOOL} from {source}. Do not edit; change DECISIONS in the tool instead.",
           "# Each '# Thoron:' comment is the reason for a deliberate choice (docs/build/RELEASE_ARGS.md)."]
    seen = set()
    for raw in upstream.splitlines():
        line = raw.strip()
        if line == "# Thoron additions":
            break             # a composed file: the additions are regenerated below
        if line.startswith("# Generated by ") or line.startswith("# Each '# Thoron:'"):
            continue
        if not line:
            continue
        m = _LINE.match(line) if not line.startswith("#") else None
        if m and m["name"] in wanted:
            d = wanted[m["name"]]
            out.append(f"{d.name} = {d.value} # Thoron: {d.reason}")
            seen.add(d.name)
        else:
            out.append(raw.rstrip())
    missing = [d for d in wanted.values() if d.name not in seen]
    if missing:
        out.append("# Thoron additions")
        out += [f"{d.name} = {d.value} # Thoron: {d.reason}" for d in missing]
    return "\n".join(out) + "\n"


def check(text: str, platform: str) -> list[str]:
    """Problems with a release args file: a decision missing or changed, or a Google key set."""
    try:
        args = parse(text)
    except ArgsError as exc:
        return [str(exc)]
    problems = []
    for d in decisions(platform):
        have = args.get(d.name)
        if have != d.value:
            problems.append(f"{d.name} must be {d.value} ({d.reason}); found {have if have is not None else 'unset'}")
    for name, value in args.items():
        if _KEY_ARGS.match(name) and value not in ('""', "''"):
            problems.append(f"{name} must not be set in a release build")
    return problems


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("compose")
    c.add_argument("--upstream", type=Path, required=True)
    c.add_argument("--platform", choices=PLATFORMS, required=True)
    c.add_argument("--source", required=True, help="upstream ref and path, written into the header")
    c.add_argument("--out", type=Path, required=True)
    k = sub.add_parser("check")
    k.add_argument("--args", type=Path, required=True)
    k.add_argument("--platform", choices=PLATFORMS, required=True)
    a = parser.parse_args(argv)
    try:
        if a.cmd == "compose":
            text = compose(a.upstream.read_text(encoding="utf-8"), a.platform, a.source)
            a.out.parent.mkdir(parents=True, exist_ok=True)
            a.out.write_text(text, encoding="ascii", newline="\n")
            print(f"wrote {a.out} ({len(decisions(a.platform))} Thoron decisions)")
            return 0
        problems = check(a.args.read_text(encoding="utf-8"), a.platform)
    except (ArgsError, OSError, UnicodeError) as exc:
        print(f"release_args: {exc}", file=sys.stderr)
        return 2
    for p in problems:
        print(f"release_args: {p}", file=sys.stderr)
    print("release args: OK" if not problems else f"release args: {len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
